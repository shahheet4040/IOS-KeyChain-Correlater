"""
ISO/IEC 27037 & NIST SP 800-86 Forensic Verification Certificate Generator
===========================================================================
Generates standardized, court-admissible Digital Forensics Verification
Certificates documenting Chain of Custody, tool provenance, and cryptographic
hashes (SHA-256) of input digital evidence and exported artifacts.
"""

from datetime import datetime, timezone
import hashlib
from pathlib import Path
import platform
import sys
from typing import Any, Dict, List, Optional


def compute_file_sha256(path: str | Path) -> str:
    """Computes SHA-256 hash of a file in streaming chunks."""
    p = Path(path)
    if not p.is_file():
        return "N/A (File Not Found)"
    h = hashlib.sha256()
    with open(p, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest().upper()


def generate_forensic_certificate(
    case_number: str,
    evidence_name: str,
    evidence_paths: List[str | Path],
    decrypted_output_paths: List[str | Path],
    examiner_name: str = "Digital Forensics Examiner",
    agency_name: str = "Digital Forensics Laboratory",
    notes: str = "",
) -> Dict[str, Any]:
    """
    Generates a structured forensic certificate conforming to ISO/IEC 27037 and NIST SP 800-86.
    """
    now_utc = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    evidence_hashes = []
    for ep in evidence_paths:
        p = Path(ep)
        evidence_hashes.append({
            "path": str(p),
            "filename": p.name,
            "sha256": compute_file_sha256(p),
            "size_bytes": p.stat().st_size if p.is_file() else 0,
        })

    output_hashes = []
    for op in decrypted_output_paths:
        p = Path(op)
        output_hashes.append({
            "path": str(p),
            "filename": p.name,
            "sha256": compute_file_sha256(p),
            "size_bytes": p.stat().st_size if p.is_file() else 0,
        })

    certificate = {
        "standard_compliance": [
            "ISO/IEC 27037:2012 (Guidelines for Digital Evidence Handling)",
            "NIST SP 800-86 (Guide to Integrating Forensic Techniques into Incident Response)",
            "Federal Rules of Evidence Rule 902(14) (Certified Records Generated by an Electronic Process)",
        ],
        "certificate_id": f"CERT-{case_number}-{datetime.now().strftime('%Y%m%d%H%M%S')}",
        "timestamp_utc": now_utc,
        "case_number": case_number,
        "evidence_name": evidence_name,
        "examiner": examiner_name,
        "agency": agency_name,
        "environment_provenance": {
            "os": f"{platform.system()} {platform.release()} ({platform.machine()})",
            "python_version": sys.version.split()[0],
            "tool_name": "iOS Keychain Correlator & Forensics Suite",
            "tool_version": "v2.4-Enterprise",
        },
        "input_evidence": evidence_hashes,
        "decrypted_outputs": output_hashes,
        "examiner_declaration": (
            "I hereby certify that the digital evidence listed herein was handled in strict "
            "adherence to forensic principles of integrity and chain of custody. The cryptographic "
            "hashes recorded represent authentic mathematical representations of the evidence."
        ),
        "notes": notes,
    }

    return certificate


def render_certificate_markdown(cert: Dict[str, Any]) -> str:
    """Renders the forensic verification certificate as formatted Markdown."""
    md = []
    md.append(f"# Digital Forensic Verification & Chain of Custody Certificate")
    md.append(f"**Certificate ID**: `{cert['certificate_id']}`  ")
    md.append(f"**Issued**: {cert['timestamp_utc']}  ")
    md.append(f"**Case Number**: {cert['case_number']}  ")
    md.append(f"**Examiner**: {cert['examiner']} | **Agency**: {cert['agency']}  \n")

    md.append("## Standards Compliance")
    for std in cert["standard_compliance"]:
        md.append(f"- **{std}**")
    md.append("")

    md.append("## Environment & Tool Provenance")
    env = cert["environment_provenance"]
    md.append(f"- **Tool**: {env['tool_name']} ({env['tool_version']})")
    md.append(f"- **OS Runtime**: {env['os']}")
    md.append(f"- **Python Runtime**: {env['python_version']}\n")

    md.append("## Input Evidence Integrity (Pre-Analysis)")
    md.append("| Evidence File | Size | SHA-256 Hash |")
    md.append("|---|---|---|")
    for ev in cert["input_evidence"]:
        md.append(f"| `{ev['filename']}` | {ev['size_bytes']:,} bytes | `{ev['sha256']}` |")
    md.append("")

    md.append("## Decrypted Output Integrity (Post-Analysis)")
    md.append("| Output File | Size | SHA-256 Hash |")
    md.append("|---|---|---|")
    for out in cert["decrypted_outputs"]:
        md.append(f"| `{out['filename']}` | {out['size_bytes']:,} bytes | `{out['sha256']}` |")
    md.append("")

    md.append("## Examiner Declaration")
    md.append(f"> *{cert['examiner_declaration']}*\n")
    md.append("```")
    md.append("Examiner Signature: ___________________________    Date: ______________")
    md.append("```\n")

    return "\n".join(md)
